import assert from 'node:assert/strict';
import {calculateDose,waterRange,positiveNumber} from '../lib/dose.mjs';
import {readFile} from 'node:fs/promises';
const data=JSON.parse(await readFile('public/data/cascara.json','utf8'));
const ortiva=data.products.find(p=>p.NumRegistro==='25588').uses[0];
const calc=(use,amount,volume,inputUnit='l',extra={})=>calculateDose(use,{amount,volume,inputUnit,...extra});
let result=calc(ortiva,'0,75','1000');assert.equal(result.perHa,.75);assert.equal(result.doseStatus,'within');assert.equal(result.waterStatus,'within');
result=calc(ortiva,'0,75','1500');assert.equal(result.perHa,1.125);assert.equal(result.overLimit,true);assert.equal(result.waterStatus,'above');
result=calc(ortiva,'1','500');assert.equal(result.perHa,.5);assert.equal(result.doseStatus,'within');assert.deepEqual(result.limitPer1000,{min:1,max:1.5});
assert.equal(calc(ortiva,'0.49','1000').belowLimit,true);
assert.equal(calc(ortiva,'750','1000','ml').doseStatus,'within');
assert.equal(calc(ortiva,'750','1000','g').checkable,false);
assert.equal(calc(ortiva,'0.75','1000','l',{extraMax:'0.7'}).overLimit,true);
assert.equal(calc(ortiva,'0.75','1000','l',{extraMax:'no'}).checkable,false);
const hl={Dosis_Min:50,Dosis_Max:100,'Unidad Medida dosis':'ml/Hl','Volumen Caldo':'500–1.000 l/ha'};
result=calc(hl,'1','800');assert.equal(result.perHa,.8);assert.equal(result.officialValue,100);assert.deepEqual(result.limitPer1000,{min:.5,max:1});
assert.equal(calc({...hl,'Unidad Medida dosis':'g/Hl'},'1000','800','g').officialValue,100);
assert.equal(calc({...hl,Dosis_Min:1,Dosis_Max:2,'Unidad Medida dosis':'Kg/ha'},'2','500','kg').doseStatus,'within');
const percent={Dosis_Min:.2,Dosis_Max:.4,'Unidad Medida dosis':'%','Volumen Caldo':'875 – 1.500 l/ha'};
assert.equal(calc(percent,'3','1000').checkable,false);
result=calc(percent,'3','1000','l',{percentBasis:'volume'});assert.equal(result.officialValue,.3);assert.equal(result.doseStatus,'within');
result=calc(percent,'3','1000','kg',{percentBasis:'mass',generalConditions:'Dosis: 3–3,5 kg/ha.'});assert.equal(result.reviewDose,true);
assert.equal(calc({...hl,'Unidad Medida dosis':'(ver nota)'},'1','1000').checkable,false);
assert.equal(calc({...hl,'Volumen Caldo':'NO APLICA'},'1','1000').checkable,false);
assert.equal(calc({...hl,Dosis_Max:0},'1','1000').checkable,false);
for(const bad of ['','0','-1','1,000,2','Infinity','1e6','NaN'])assert.equal(positiveNumber(bad),null);
assert.equal(calc(ortiva,'1','0').ready,false);
assert.deepEqual(waterRange({'Volumen Caldo':'300 - 1.000 l/ha'}),{min:300,max:1000});
assert.equal(waterRange({'Volumen Caldo':'Invierno: 500-1000 l/ha. Verano: 1000-2000 l/ha.'}),null);
assert.equal(waterRange({'Volumen Caldo':'Uso profesional: 500-1000 l/ha; no profesional: 5-10 l/100m2'}),null);
console.log('Dosis: límites por hectárea, concentración, unidades, porcentajes, caldo y datos no validables: OK');
