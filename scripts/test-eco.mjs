import assert from 'node:assert/strict';
import fs from 'node:fs';
import { classifyEco } from '../lib/eco.mjs';
const product = (names, uses, extra = {}) => ({ Estado: 'Vigente', composition: names.map(NombreUE => ({ NombreUE })), uses, ...extra });
const spray = { Agente: 'Mosca de la fruta, Ceratitis capitata', MetodoAplicacion: 'Pulverización foliar' };
const trap = { Agente: 'Mosca de la fruta, Ceratitis capitata', 'Unidad Medida dosis': 'Trampa/ha' };
assert.equal(classifyEco(product(['Sulphur'], [spray])).eligible, true);
assert.equal(classifyEco(product(['Sulphur', 'Glyphosate'], [spray])).eligible, false);
assert.equal(classifyEco(product(['Sulphurish'], [spray])).status, 'not-established');
assert.equal(classifyEco(product(['Sulphur'], [spray], { Estado: 'Cancelado' })).eligible, false);
assert.equal(classifyEco(product(['Deltamethrin'], [spray])).eligible, false);
assert.equal(classifyEco(product(['lambda-Cyhalothrin'], [spray])).eligible, false);
assert.deepEqual(classifyEco(product(['Deltamethrin'], [spray, trap])).useIndexes, [1]);
assert.equal(classifyEco(product(['Deltamethrin'], [{ ...trap, Agente: 'Eurytoma amygdali' }])).eligible, false);
assert.equal(classifyEco(product(['Copper hydroxide'], [spray])).conditional, true);
assert.match(classifyEco(product(['Copper hydroxide'], [spray])).conditions[0], /28 kg.*7 años/);
assert.equal(classifyEco(product(['Orange oil'], [{ Agente: 'Malas hierbas' }])).eligible, false);
assert.equal(classifyEco(product(['Laminarin'], [spray])).conditional, true);
const pistacho = JSON.parse(fs.readFileSync(new URL('../public/data/pistacho.json', import.meta.url))).products;
assert.equal(classifyEco(pistacho.find(p => p.Nombre === 'LAMBDASTAR')).eligible, false);
assert.equal(classifyEco(pistacho.find(p => p.Nombre === 'DECIS TRAP')).eligible, true);
assert.equal(classifyEco(pistacho.find(p => p.Nombre === 'ORTIVA TOP')).eligible, false);
assert.equal(classifyEco(pistacho.find(p => p.Nombre === 'DELMUR TRAP')).conditional, true);
console.log('ECO: mixtures, unknown, canceled, use restrictions, copper, origin and official sample cases OK');
